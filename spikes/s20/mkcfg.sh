#!/usr/bin/env bash
# Writes the TLC configs for PairReplication.tla. Run from spikes/s20.
set -euo pipefail

# cfg NAME FAULTS DOWN SWITCHOVERS "SWITCH=VALUE ..." "CHECKS"
# FAULTS: faults over the run (-1: no bound); DOWN: components failed at once.
# CHECKS: INVARIANT and PROPERTY lines, separated by ';'.
cfg() {
    local name=$1 faults=$2 down=$3 switchovers=$4 overrides=$5 checks=$6
    declare -A c=(
        [Outdated]=TRUE [ReportOnlyInSync]=TRUE [CommitWhileRunning]=TRUE
        [DurableAck]=TRUE [ReadBarrier]=TRUE [LeaseReads]=TRUE [KeepSuffix]=TRUE
        [Crashes]=TRUE [LanFaults]=TRUE [SerialFaults]=TRUE [WanFaults]=TRUE
        [WitnessCrashes]=TRUE [Compaction]=TRUE
    )
    local kv
    for kv in $overrides; do c[${kv%%=*}]=${kv#*=}; done
    {
        echo "\\* Generated by mkcfg.sh."
        echo "SPECIFICATION Spec"
        echo
        echo "CONSTANTS"
        echo "    A = A"
        echo "    B = B"
        echo "    MaxEpoch = 3"
        echo "    MaxWrites = 2"
        echo "    MaxLog = 3"
        echo "    QueueLen = 1"
        if [ "$faults" = -1 ]; then echo "    MaxFaults <- NoBound"; else echo "    MaxFaults = $faults"; fi
        echo "    MaxDown = $down"
        echo "    MaxSwitchovers = $switchovers"
        local k
        for k in Crashes LanFaults SerialFaults WanFaults WitnessCrashes Compaction \
                 Outdated ReportOnlyInSync CommitWhileRunning DurableAck ReadBarrier LeaseReads KeepSuffix; do
            echo "    $k = ${c[$k]}"
        done
        echo
        echo "$checks" | tr ';' '\n' | sed 's/^ *//'
    } > "$name.cfg"
}

SAFETY="INVARIANT TypeOK;INVARIANT AtMostOneRunning;INVARIANT CommittedAgree;INVARIANT LeaderComplete;INVARIANT ReadLinearizable;PROPERTY NoLostWrite;PROPERTY CommittedStable"

# The guarantee: one failure at a time, any number over time, and a planned
# switchover. Design1: one fault in the whole run (a subset of DesignSeq).
cfg DesignSeq -1 1 1 "" "$SAFETY"
cfg Design1 1 9 1 "" "$SAFETY"

# Each rule switched off, one failure at a time; each should fail.
cfg NoOutdated -1 1 1 "Outdated=FALSE" "$SAFETY"
cfg NoReportInSync -1 1 1 "ReportOnlyInSync=FALSE" "$SAFETY"
cfg NoDurableAck -1 1 1 "DurableAck=FALSE" "$SAFETY"
cfg NoReadBarrier -1 1 1 "ReadBarrier=FALSE" "$SAFETY"
cfg NoKeepSuffix -1 1 1 "KeepSuffix=FALSE" "$SAFETY"

# Beyond the guarantee, by random simulation: two failures at once; and the
# lease rules, which need three (LAN, serial and the primary's WAN) before a
# primary loses its lease while it still leads.
cfg Sim2Design 2 2 1 "" "$SAFETY"
cfg Sim3NoLeaseReads 3 3 1 "LeaseReads=FALSE" "$SAFETY"
cfg Sim3NoCommitRunning 3 3 1 "CommitWhileRunning=FALSE" "$SAFETY"

# Vacuity: each must be violated.
cfg Vac_WriteAfterFailover -1 1 0 "" "INVARIANT NoWriteAfterFailover"
cfg Vac_AloneCommit -1 1 0 "" "PROPERTY NoAloneCommit"
cfg Vac_SnapshotCatchUp -1 1 0 "" "PROPERTY NoSnapshotCatchUp"
cfg Vac_Truncate -1 1 0 "" "PROPERTY NoTruncate"
cfg Vac_Refusal -1 1 0 "" "INVARIANT NoRefusal"
cfg Vac_Report -1 1 0 "" "PROPERTY NoReport"
cfg Vac_ReadAfterFailover -1 1 0 "" "INVARIANT NoReadAfterFailover"
cfg Vac_Handover -1 1 1 "" "INVARIANT NoHandover"

# The lease rules exhaustively, with link faults only (no crashes), three at once.
cfg Links3NoLeaseReads 3 3 0 "LeaseReads=FALSE Crashes=FALSE WitnessCrashes=FALSE" "$SAFETY"
cfg Links3NoCommitRunning 3 3 0 "CommitWhileRunning=FALSE Crashes=FALSE WitnessCrashes=FALSE" "$SAFETY"
